# Re-exec the calling test script inside an unprivileged user + network
# namespace (unshare -nr).  Inside it we are mapped to root with full
# capabilities over any namespace we create, so none of the ip/tc/tuntap
# plumbing below needs sudo.  Call it right after sourcing this file,
# forwarding the script arguments:
#
#   enter_test_namespace "$@"
function enter_test_namespace() {
  if [ -n "${ZPR_TEST_IN_USERNS:-}" ]
  then
    # Already inside; bring up loopback in the orchestration namespace.
    ip link set lo up
    return 0
  fi

  if ! unshare -nr true 2> /dev/null
  then
    echo "ERROR: cannot create an unprivileged user+network namespace (unshare -nr)." >&2
    echo "On Ubuntu 24.04+ this is usually AppArmor's user-namespace restriction;" >&2
    echo "a one-time admin fix is:" >&2
    echo "  echo kernel.apparmor_restrict_unprivileged_userns=0 | sudo tee /etc/sysctl.d/60-zpr-userns.conf" >&2
    echo "  sudo sysctl --system" >&2
    exit 1
  fi

  export ZPR_TEST_IN_USERNS=1
  exec unshare -nr "$0" "$@"
}

# Each test network namespace is an anonymous netns pinned by a holder
# process; NETNS_PID maps namespace name -> holder pid.  No /run/netns
# entries and no root privileges are involved, and when the holders die the
# namespaces evaporate, so a crashed test cannot leak namespaces into the
# host.
declare -A NETNS_PID

function new_netns() {
  local NAME=$1

  unshare -n sleep infinity &
  local PID=$!

  # Wait until the holder has actually unshared its network namespace;
  # entering it before that would target the orchestration namespace.
  local OUR_NS HOLDER_NS
  OUR_NS=$(readlink "/proc/$$/ns/net")
  for ((i = 0; i < 50; ++i))
  do
    HOLDER_NS=$(readlink "/proc/$PID/ns/net" 2> /dev/null || true)
    if [ -n "$HOLDER_NS" ] && [ "$HOLDER_NS" != "$OUR_NS" ]
    then
      NETNS_PID[$NAME]=$PID
      return 0
    fi
    sleep 0.1
  done

  echo "failed to create network namespace $NAME" >&2
  return 1
}

# Run a command in a test namespace created by new_netns.
# NOTE: unlike `ip netns exec`, this only enters the network namespace and
# does not remount /sys, so read interface state via `ip link`, not
# /sys/class/net.
function in_ns() {
  local NAME=$1
  shift
  nsenter -t "${NETNS_PID[$NAME]}" -n -- "$@"
}

# Create a veth pair in the orchestration namespace and move one end into
# each of two test namespaces.  The test namespaces are freshly created, so
# explicit names cannot collide (the old `ip netns` flow had to rely on
# kernel-autogenerated names to dodge a root-namespace name clash).
function connect_ns() {
  local NS_A=$1 IF_A=$2 NS_B=$3 IF_B=$4

  ip link add "$IF_A" type veth peer name "$IF_B"
  ip link set "$IF_A" netns "${NETNS_PID[$NS_A]}"
  ip link set "$IF_B" netns "${NETNS_PID[$NS_B]}"
}

function prefix_log() {
  SYSNAME=$1
  printf -v PREFIX '%10s' "[$SYSNAME]"
  sed "s/^/$PREFIX /"
}

function wait_for() {
  RETRIES=$1
  shift
  CMD=("$@")

  if "${CMD[@]}"
  then return 0
  else RET=$?
  fi

  for ((i = 0; i < RETRIES; ++i))
  do
    sleep 1

    if "${CMD[@]}"
    then return 0
    else RET=$?
    fi
  done

  return "$RET"
}

function create_network() {
  new_netns zpr-node
  new_netns zpr-vs
  new_netns zpr-a
  new_netns zpr-b
  new_netns zpr-c

  # loopback

  in_ns zpr-node ip link set lo up
  in_ns zpr-vs ip link set lo up
  in_ns zpr-a ip link set lo up
  in_ns zpr-b ip link set lo up
  in_ns zpr-c ip link set lo up

  # virtual Ethernet pairs

  connect_ns zpr-vs veth0 zpr-node veth-zpr-vs
  connect_ns zpr-a veth0 zpr-node veth-zpr-a
  connect_ns zpr-b veth0 zpr-node veth-zpr-b
  connect_ns zpr-c veth0 zpr-node veth-zpr-c

  in_ns zpr-node ip addr add "$NODE_SUBSTRATE_ADDR_VS" peer "$VS_SUBSTRATE_ADDR" dev veth-zpr-vs
  in_ns zpr-node ip addr add "$NODE_SUBSTRATE_ADDR_A" peer "$A_SUBSTRATE_ADDR" dev veth-zpr-a
  in_ns zpr-node ip addr add "$NODE_SUBSTRATE_ADDR_B" peer "$B_SUBSTRATE_ADDR" dev veth-zpr-b
  in_ns zpr-node ip addr add "$NODE_SUBSTRATE_ADDR_C/24" dev veth-zpr-c
  if [ -n "${NODE_SUBSTRATE_ADDR_C_ALT-}" ]
  then in_ns zpr-node ip addr add "$NODE_SUBSTRATE_ADDR_C_ALT/24" dev veth-zpr-c  # Used for testing routing.
  fi
  in_ns zpr-vs ip addr add "$VS_SUBSTRATE_ADDR" peer "$NODE_SUBSTRATE_ADDR_VS" dev veth0
  in_ns zpr-a ip addr add "$A_SUBSTRATE_ADDR" peer "$NODE_SUBSTRATE_ADDR_A" dev veth0
  in_ns zpr-b ip addr add "$B_SUBSTRATE_ADDR" peer "$NODE_SUBSTRATE_ADDR_B" dev veth0
  in_ns zpr-c ip addr add "$C_SUBSTRATE_ADDR/24" dev veth0

  in_ns zpr-node ip link set veth-zpr-vs up
  in_ns zpr-node ip link set veth-zpr-a up
  in_ns zpr-node ip link set veth-zpr-b up
  in_ns zpr-node ip link set veth-zpr-c up
  in_ns zpr-vs ip link set veth0 up
  in_ns zpr-a ip link set veth0 up
  in_ns zpr-b ip link set veth0 up
  in_ns zpr-c ip link set veth0 up

  # TUN devices.  No `user` option: everything runs as the namespace's
  # mapped root, which holds CAP_NET_ADMIN over these devices anyway.

  in_ns zpr-node ip tuntap add name tun0 mode tun multi_queue
  in_ns zpr-vs ip tuntap add name tun0 mode tun multi_queue
  in_ns zpr-a ip tuntap add name tun0 mode tun multi_queue
  in_ns zpr-b ip tuntap add name tun0 mode tun multi_queue
  in_ns zpr-c ip tuntap add name tun0 mode tun multi_queue

  in_ns zpr-node ip link set tun0 up
  in_ns zpr-vs ip link set tun0 up
  in_ns zpr-a ip link set tun0 up
  in_ns zpr-b ip link set tun0 up
  in_ns zpr-c ip link set tun0 up

  # Kernel bug: kernels older than 6.10 don't set peer route correctly
  # when interface is down.  I think <https://github.com/torvalds/linux/commit/d0098e4c6b83e502cc1cd96d67ca86bc79a6c559>
  # fixes this issue.  For now, add the addresses after we bring the link up.
  in_ns zpr-node ip addr add "$NODE_ZPR_ADDR" peer "$VS_ZPR_ADDR" dev tun0
  in_ns zpr-vs ip addr add "$VS_ZPR_ADDR" peer "$NODE_ZPR_ADDR" dev tun0
  in_ns zpr-a ip addr add "$A_ZPR_ADDR" peer "$ZPR_SUBNET" dev tun0
  in_ns zpr-b ip addr add "$B_ZPR_ADDR" peer "$ZPR_SUBNET" dev tun0
  in_ns zpr-c ip addr add "$C_ZPR_ADDR" peer "$ZPR_SUBNET" dev tun0
}

function configure_netem() {
  echo "Configuring netem $@" > /dev/stderr
  for NIC in vs a b c
  do
    in_ns zpr-node tc qdisc add dev veth-zpr-"$NIC" root netem "$@"
  done
}

function destroy_network() {
  # The namespaces are anonymous, pinned only by their holder processes;
  # killing the holders destroys them.
  local NAME
  for NAME in "${!NETNS_PID[@]}"
  do
    kill "${NETNS_PID[$NAME]}" 2> /dev/null || true
  done
  NETNS_PID=()
}

