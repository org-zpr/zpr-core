function ping_test() {
  RESULT=0

  in_ns zpr-node ping -q -c 5 -w 5 "$VS_ZPR_ADDR" & wait -f $!; let RESULT="RESULT||$?"
  in_ns zpr-vs ping -q -c 5 -w 5 "$NODE_ZPR_ADDR" & wait -f $!; let RESULT="RESULT||$?"
  in_ns zpr-a ping -q -c 5 -w 5 "$B_ZPR_ADDR" & wait -f $!; let RESULT="RESULT||$?"
  in_ns zpr-b ping -q -c 5 -w 5 "$A_ZPR_ADDR" & wait -f $!; let RESULT="RESULT||$?"

  if [[ "$NUM_ACTORS" -ge 3 ]]; then
    in_ns zpr-a ping -q -c 5 -w 5 "$C_ZPR_ADDR" & wait -f $!; let RESULT="RESULT||$?"
    in_ns zpr-b ping -q -c 5 -w 5 "$C_ZPR_ADDR" & wait -f $!; let RESULT="RESULT||$?"
    in_ns zpr-c ping -q -c 5 -w 5 "$A_ZPR_ADDR" & wait -f $!; let RESULT="RESULT||$?"
    in_ns zpr-c ping -q -c 5 -w 5 "$B_ZPR_ADDR" & wait -f $!; let RESULT="RESULT||$?"
  fi

  return "$RESULT"
}

function check_carrier() {
  NETNS=$1
  IF=$2

  # `nsenter -n` does not remount /sys (unlike `ip netns exec`), so
  # /sys/class/net would show the wrong namespace; ask ip(8) instead.
  in_ns "$NETNS" ip link show dev "$IF" | grep -q LOWER_UP
}

# Visible sleep for n seconds.  Takes one arg: number of seconds.
function countdown() {
    count=$1
    (( ++count ))
    while (( --count > 0 )); do
        echo -n "$count...   "
        sleep 1
    done
    echo
}

# Get all descendant PIDs whose name matches a specific list
function get_descendants() {
    exenames="(ph|node|adapter|vservice|vs|valkey-server)"
    regex="$exenames\(([0-9]+)\)"
    echo $(pstree -pT "$$" | egrep -o "$regex" | sed -E "s/$regex/\2/")
}

# Takes one arg- filepath relative to TMPDIR
function emitlog() {
    echo -e "\n\n==== $1 ====\n"
    if [ -e "$TMPDIR/$1" ]
        then
            cat "$TMPDIR/$1"
        else
            echo "(MISSING)"
    fi
}


function cleanup() {
  # Kill the known test processes (ph/vs/valkey and the netns holders) first:
  # `jobs -p` only yields each pipeline's leader, and killing that leaves the
  # actual daemons running with the `tee`s still holding their pipes, which
  # would make the `wait -f` below hang until the CI job times out whenever a
  # test aborts mid-run.
  for pid in $(get_descendants)
  do kill -9 "$pid" 2> /dev/null || true
  done

  for child in $(jobs -p)
  do kill -9 "$child" 2> /dev/null || true
  done

  wait -f

  destroy_network || true

  SHOW_LOGS="${ZPR_TEST_VERBOSE:-no}"

  if [ "$SHOW_LOGS" != "no" ]
     then
         emitlog "node.log"
         emitlog "vs.log"
         emitlog "adapter1.log"
         emitlog "adapter2.log"
         emitlog "adapter3.log"
  fi

  popd > /dev/null
  rm -r "$TMPDIR" || true
}
